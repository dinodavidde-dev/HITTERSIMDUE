/**
 * Returns a localized version of a radio script.
 * If language is English (isEn = true), replaces Italian strings with their English counterparts.
 */
export function getLocalizedRadioScript(
  script: TimelineRegiaRadioScript,
  isEn: boolean
): TimelineRegiaRadioScript {
  if (!isEn) return script;
  const translation = TIMELINE_REGIA_RADIO_TRANSLATIONS_EN[script.code];
  if (!translation) return script;

  return {
    ...script,
    checkpoint: translation.checkpoint,
    channelLabel: translation.channelLabel,
    sender: translation.sender,
    recipient: translation.recipient,
    phaseTitle: translation.phaseTitle,
    scriptText: translation.scriptText,
    operationalNotes: translation.operationalNotes,
    actionRequired: translation.actionRequired,
  };
}
